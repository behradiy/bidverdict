#!/usr/bin/env bash
# Builds the Chrome Web Store upload with your API URL baked in.
# Usage: ./scripts/package-extension.sh https://bidverdict-api-xxxxxxxx-uc.a.run.app
set -euo pipefail
cd "$(dirname "$0")/.."

API="${1:?Pass your Cloud Run URL, e.g. https://bidverdict-api-abc123-uc.a.run.app}"
API="${API%/}"
if [[ ! "$API" =~ ^https://[A-Za-z0-9.-]+$ ]]; then
  echo "Use the https:// service URL with no path." >&2
  exit 1
fi

VERSION=$(python3 -c "import json; print(json.load(open('extension/manifest.json'))['version'])")
OUT="dist/govverdict-$VERSION.zip"
rm -rf dist/extension "$OUT"
mkdir -p dist
cp -r extension dist/extension
printf "// Generated by scripts/package-extension.sh\nexport const API_BASE = '%s';\n" "$API" > dist/extension/config.js

if grep -rq "localhost" dist/extension; then
  echo "Build still references localhost; aborting." >&2
  exit 1
fi

python3 - "$OUT" <<'PY'
import os, sys, zipfile
out = sys.argv[1]
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for root, _, files in os.walk("dist/extension"):
        for f in sorted(files):
            if f.startswith("."):
                continue
            p = os.path.join(root, f)
            z.write(p, os.path.relpath(p, "dist/extension"))
print("Built", out, f"({os.path.getsize(out) // 1024} KB)")
PY
echo "Load dist/extension as an unpacked extension to test, then upload $OUT to the Chrome Web Store."
